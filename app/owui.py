"""Shared Open-WebUI API client.

One request helper for the context router, with explicit
headers: the caller must always pass the ``Authorization`` header for the
acting identity. There is deliberately **no** implicit fallback to the
static ``OWUI_TOKEN`` — a fail-closed module must not silently pick a
credential the caller did not ask for.

Production requests reuse the ``httpx.AsyncClient`` created in the app
lifespan (``app.state.owui_client``) so connections are pooled; code
paths without a ``Request`` (background jobs, tests) fall back to a
short-lived per-call client.
"""

import httpx
from fastapi import Request

from app.config import settings
from app.errors import ConfigError, OWUIError
from app.logging import get_logger

logger = get_logger(__name__)

DEFAULT_TIMEOUT = 60.0


def shared_client(request: Request | None) -> httpx.AsyncClient | None:
    """Return the app-level shared client, or ``None`` when unavailable
    (no ``Request`` in scope, or the app ran without lifespan)."""
    if request is None:
        return None
    return getattr(request.app.state, "owui_client", None)


async def owui_request(
    method: str,
    path: str,
    *,
    auth_headers: dict,
    request: Request | None = None,
    client: httpx.AsyncClient | None = None,
    timeout: float = DEFAULT_TIMEOUT,
    **kwargs,
) -> dict:
    """Make a request to the Open-WebUI API with error handling.

    ``auth_headers`` must carry the ``Authorization`` header for the
    acting identity; a missing header is a :class:`ConfigError`, not a
    silent static-token fallback.
    """
    settings.require_owui_config()
    if not isinstance(auth_headers, dict) or "Authorization" not in auth_headers:
        raise ConfigError(
            "Open-WebUI request is missing the Authorization header "
            "(acting identity is required)"
        )

    url = f"{settings.owui_api_url}{path}"
    headers = {
        "Accept": "application/json",
        **auth_headers,
    }
    # Only force the JSON content type for plain JSON bodies: with
    # files=/data= the content type must be multipart/form-data (the
    # boundary is generated by httpx and would be masked otherwise).
    if "files" not in kwargs and "data" not in kwargs:
        headers["Content-Type"] = "application/json"

    if client is None:
        client = shared_client(request)
    try:
        if client is not None:
            response = await client.request(
                method, url, headers=headers, timeout=timeout, **kwargs
            )
        else:
            async with httpx.AsyncClient(
                timeout=timeout, follow_redirects=True
            ) as ephemeral:
                response = await ephemeral.request(
                    method, url, headers=headers, **kwargs
                )
    except httpx.RequestError as e:
        raise OWUIError(f"Failed to connect to Open-WebUI: {e}") from e

    return _parse(response, method, path)


def _parse(response: httpx.Response, method: str, path: str) -> dict:
    try:
        response.raise_for_status()
    except httpx.HTTPStatusError as e:
        try:
            detail = e.response.json().get("detail")
            if not isinstance(detail, str):
                detail = str(detail)
        except ValueError:
            detail = e.response.text[:500]
        logger.error(
            "Open-WebUI API request failed",
            method=method,
            path=path,
            status_code=e.response.status_code,
            detail=detail[:500],
        )
        raise OWUIError(
            f"Open-WebUI API error {e.response.status_code}: {detail[:500]}",
            status_code=e.response.status_code,
        ) from e
    try:
        return response.json()
    except ValueError as e:
        raise OWUIError(
            f"Open-WebUI returned a non-JSON response ({method} {path})",
            status_code=502,
        ) from e
